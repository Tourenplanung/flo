function words(s: string): string[] {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
}

function pascal(s: string, fallback: string): string {
  let out = words(s)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('');
  if (!out) out = fallback;
  if (/^[0-9]/.test(out)) out = `${fallback}${out}`;
  return out;
}

function camel(s: string, fallback: string): string {
  const p = pascal(s, fallback);
  return p[0]!.toLowerCase() + p.slice(1);
}

const RESERVED = new Set(['App', 'React', 'Fragment', 'PrototypeProvider', 'PrototypeView', 'Screen', 'Object', 'String', 'Array', 'Map', 'Set', 'Image']);

class Names {
  private used = new Set<string>(RESERVED);
  take(base: string): string {
    let n = base;
    let i = 2;
    while (this.used.has(n)) n = `${base}${i++}`;
    this.used.add(n);
    return n;
  }
}

