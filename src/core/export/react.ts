type Lookup = (id: string) => DesignNode | undefined;

interface CompInfo {
  name: string;
  main: FrameNode;
  /** source layer id → prop key */
  keys: Map<string, string>;
  textKeys: string[];
  imageKeys: string[];
}

interface Unit {
  file: string;
  styles: StyleBuilder;
  prefix: string;
  counter: number;
  componentImports: Set<string>;
  icons: Set<string>;
  usesProto: boolean;
  /** Set while rendering a component's own file. */
  comp: CompInfo | null;
}

const EXT: Record<string, string> = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/gif': 'gif' };

export async function exportReactProject(
  project: Project,
  rootIds: string[],
  opts: { name: string; lang: 'it' | 'en' },
  host: ReactExportHost = {},
): Promise<ReactExportResult> {
  const warnings: string[] = [];
  const files: ExportFile[] = [];
  const lookup: Lookup = (id) => project.nodes[id];
  const screenIds = rootIds.filter((id) => project.nodes[id]?.type === 'frame');
  if (!screenIds.length) throw new Error(opts.lang === 'it' ? 'Nessun frame da esportare' : 'No frames to export');

  const names = new Names();
  const screenKey = new Map<string, string>();
  for (const id of screenIds) screenKey.set(id, names.take(pascal(project.nodes[id]!.name, 'Screen')));

  /* ---------- assets ---------- */
  const assetPath = new Map<string, string>();
  const assetSlugs = new Names();
  const pathFor = (assetId: string): string | null => {
    const meta = project.assets[assetId];
    if (!meta) return null;
    let p = assetPath.get(assetId);
    if (!p) {
      p = `/assets/${assetSlugs.take(camel(meta.name.replace(/\.[a-z0-9]+$/i, ''), 'image'))}.${EXT[meta.mimeType] ?? 'png'}`;
      assetPath.set(assetId, p);
    }
    return p;
  };

  /* ---------- components ---------- */
  const comps = new Map<string, CompInfo>();
  const compFor = (mainId: string): CompInfo | null => {
    const existing = comps.get(mainId);
    if (existing) return existing;
    const main = project.nodes[mainId];
    if (!main || main.type !== 'frame' || !main.component) return null;
    const info: CompInfo = { name: names.take(pascal(main.name, 'Component')), main, keys: new Map(), textKeys: [], imageKeys: [] };
    const keyNames = new Names();
    const visit = (id: string) => {
      const n = project.nodes[id];
      if (!n) return;
      const k = keyNames.take(camel(n.name, n.type));
      info.keys.set(id, k);
      if (n.type === 'text') info.textKeys.push(k);
      if (n.type === 'image') info.imageKeys.push(k);
      if (n.type !== 'instance') n.childIds.forEach(visit);
    };
    main.childIds.forEach(visit);
    comps.set(mainId, info);
    return info;
  };

  /* ---------- interactions ---------- */
  const actionsJs = (list: Interaction[]): string | null => {
    const out: unknown[] = [];
    for (const i of list) {
      const a: InteractionAction = i.action;
      if (a.type === 'navigate' || a.type === 'open-overlay') {
        const to = screenKey.get(a.destinationId);
        if (!to) {
          warnings.push(opts.lang === 'it' ? `Interazione verso una schermata non esportata (${project.nodes[a.destinationId]?.name ?? a.destinationId})` : `Interaction to a screen that was not exported (${project.nodes[a.destinationId]?.name ?? a.destinationId})`);
          continue;
        }
        out.push(a.type === 'navigate' ? { type: 'navigate', to, transition: a.transition } : { type: 'open-overlay', to, position: a.position, closeOnOutsideClick: a.closeOnOutsideClick, dimBackground: a.dimBackground });
      } else if (a.type === 'toggle-visibility') out.push({ type: 'toggle-visibility', target: a.targetId });
      else out.push({ type: a.type });
    }
    return out.length ? js(out) : null;
  };
  const toggleTargets = new Set<string>();
  for (const n of Object.values(project.nodes)) for (const i of n.interactions) if (i.action.type === 'toggle-visibility') toggleTargets.add(i.action.targetId);

  /* ---------- rendering ---------- */
  const newUnit = (file: string, prefix: string, comp: CompInfo | null): Unit => ({
    file,
    styles: new StyleBuilder(project),
    prefix,
    counter: 0,
    componentImports: new Set(),
    icons: new Set(),
    usesProto: false,
    comp,
  });

  const scopeExpr = (u: Unit) => (u.comp ? 'props.pid' : 'undefined');

  const render = async (n: DesignNode, look: Lookup, depth: number, u: Unit, opt: { root?: 'screen' | 'component'; parent: DesignNode | null; srcId?: string }): Promise<string> => {
    const pad = '  '.repeat(depth + 3);
    if (n.type === 'instance') return renderInstance(n, look, depth, u, opt.parent);
    const visibleSomewhere = n.visible || Object.values(n.responsive).some((o) => o.visible);
    const compKey = u.comp && opt.srcId ? u.comp.keys.get(opt.srcId) : undefined;
    if (!visibleSomewhere && !toggleTargets.has(n.id) && !compKey) return '';

    const cls = `${u.prefix}-${++u.counter}`;
    const decl = u.styles.add(cls, n, opt.parent, opt.root === 'screen');
    const r = resolveNode(n, project.tokens, []);
    const attrs: string[] = [];
    let className = js(cls);
    if (opt.root === 'component') className = `{[${js(cls)}, props.className].filter(Boolean).join(' ')}`;
    else className = `{${className}}`;
    // Component roots accept handlers from the instance (e.g. its prototype interactions).
    if (opt.root === 'component') attrs.push('{...props.rootProps}');
    attrs.push(`className=${className}`);
    if (compKey) attrs.push(`style={props.styles?.${compKey}}`);

    // Interactions
    const clicks = actionsJs(n.interactions.filter((i) => i.trigger === 'click'));
    const hovers = actionsJs(n.interactions.filter((i) => i.trigger === 'hover'));
    let tag = r.type === 'text' ? TEXT_TAG[r.role] : r.type === 'frame' ? FRAME_TAG[r.role] : 'div';
    if (r.type === 'image' || r.type === 'icon' || r.type === 'line') tag = 'span';
    if (clicks || hovers) u.usesProto = true;
    if (clicks) {
      attrs.push(`onClick={(e) => { e.stopPropagation(); ${tag === 'a' ? 'e.preventDefault(); ' : ''}proto.run(${clicks}, ${scopeExpr(u)}); }}`);
      if (tag !== 'button' && tag !== 'a') {
        attrs.push('role="button"', 'tabIndex={0}');
        attrs.push(`onKeyDown={(e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); proto.run(${clicks}, ${scopeExpr(u)}); } }}`);
      }
    }
    if (hovers) {
      attrs.push(`onMouseEnter={() => proto.hover(${hovers}, true, ${scopeExpr(u)})}`, `onMouseLeave={() => proto.hover(${hovers}, false, ${scopeExpr(u)})}`);
    }
    if (tag === 'button') attrs.push('type="button"');
    if (tag === 'a') {
      attrs.push('href="#"');
      if (!clicks) attrs.push('onClick={(e) => e.preventDefault()}');
    }
    if (r.type === 'frame' && r.role === 'input') attrs.push('role="textbox"', 'aria-readonly="true"');

    // Children / content
    let inner = '';
    if (r.type === 'text') {
      inner = compKey ? `{props.texts?.${compKey} ?? ${js(r.characters)}}` : `{${js(r.characters)}}`;
    } else if (r.type === 'image') {
      const src = r.assetId ? pathFor(r.assetId) : null;
      const srcExpr = compKey ? `props.images?.${compKey} ?? ${js(src)}` : js(src);
      if (src || compKey) {
        inner = `{(${srcExpr}) ? <img src={(${srcExpr}) ?? undefined} alt=${`{${js(r.alt)}}`} style={{ width: '100%', height: '100%', objectFit: ${js(r.fit)}, borderRadius: 'inherit' }} /> : null}`;
      }
      attrs.push('role="img"', `aria-label={${js(r.alt || r.name)}}`);
    } else if (r.type === 'icon') {
      const icon = lucideName(r.icon);
      u.icons.add(icon);
      inner = `<Icon${icon} width="100%" height="100%" strokeWidth={${r.strokeWidth}} aria-hidden="true" />`;
    } else if (r.type === 'line') {
      const s = r.stroke;
      inner = `<svg width={${r.width}} height={${Math.max(r.height, 1)}} style={{ overflow: 'visible' }} aria-hidden="true"><line x1={0} y1={${r.flip ? r.height : 0}} x2={${r.width}} y2={${r.flip ? 0 : r.height}} stroke=${js(s?.color ?? '#000')} strokeOpacity={${s?.opacity ?? 1}} strokeWidth={${s?.width ?? 1}} /></svg>`;
    } else {
      const parts: string[] = [];
      for (const cid of r.childIds) {
        const child = look(cid);
        if (child) parts.push(await render(child, look, depth + 1, u, { parent: r, srcId: u.comp ? cid : undefined }));
      }
      inner = parts.filter(Boolean).length ? `\n${parts.filter(Boolean).join('')}${pad}` : '';
    }

    let element = `${pad}<${tag} ${attrs.join(' ')}>${inner}</${tag}>\n`;
    // Visibility: component overrides and prototype toggles.
    const shown = decl.display === 'none' ? (r.type === 'frame' && r.layout.mode !== 'none' ? 'flex' : 'block') : null;
    const baseVisible = r.visible;
    const conditions: string[] = [];
    if (compKey) conditions.push(`(props.visible?.${compKey} ?? ${baseVisible})`);
    if (toggleTargets.has(n.id) || (opt.srcId && toggleTargets.has(opt.srcId))) {
      u.usesProto = true;
      conditions.push(`proto.isVisible(${js(opt.srcId ?? n.id)}, ${baseVisible}, ${scopeExpr(u)})`);
    }
    if (conditions.length) {
      const styleShow = shown ? (compKey ? ` style={{ ...props.styles?.${compKey}, display: ${js(shown)} }}` : ` style={{ display: ${js(shown)} }}`) : '';
      if (shown) element = element.replace(compKey ? `style={props.styles?.${compKey}}` : `className=${className}`, compKey ? styleShow.trim() : `className=${className}${styleShow}`);
      element = `${pad}{${conditions.join(' && ')} ? (\n${element.replace(/^/gm, '  ')}${pad}) : null}\n`;
    }
    return element;
  };

  const renderInstance = async (inst: DesignNode & { type: 'instance' }, look: Lookup, depth: number, u: Unit, parent: DesignNode | null): Promise<string> => {
    const pad = '  '.repeat(depth + 3);
    const main = getMainComponent(project, inst);
    const exp = expandInstance(project, inst);
    if (!main || !exp) {
      warnings.push(`Instance “${inst.name}” has no main component`);
      return '';
    }
    const info = compFor(main.id)!;
    if (u.comp?.main.id !== info.main.id) u.componentImports.add(info.name);
    const cls = `${u.prefix}-${++u.counter}`;
    // The instance's own geometry (position/size) in its parent; content styles come from the component.
    u.styles.add(cls, exp.root, parent, false);
    const props: string[] = [`className=${js(cls)}`];
    props.push(u.comp ? `pid={[props.pid, ${js(inst.id)}].filter(Boolean).join('/')}` : `pid=${js(inst.id)}`);
    const texts: Record<string, string> = {};
    const visible: Record<string, boolean> = {};
    const images: Record<string, string> = {};
    const styles: Record<string, CSSDecl> = {};
    const sb = new StyleBuilder(project);
    for (const [srcId, ov] of Object.entries(inst.overrides)) {
      const k = info.keys.get(srcId);
      const src = project.nodes[srcId];
      if (!k || !src) continue;
      if (ov.characters !== undefined) texts[k] = ov.characters;
      if (ov.visible !== undefined) visible[k] = ov.visible;
      if (ov.assetId) {
        const p = pathFor(ov.assetId);
        if (p) images[k] = p;
      }
      const srcParent = project.nodes[src.parentId] ?? null;
      const styleOv = { ...ov };
      delete styleOv.characters;
      delete styleOv.visible;
      delete styleOv.assetId;
      delete styleOv.icon;
      if (Object.keys(styleOv).length) {
        const d = diffDecl(sb.decl(src, srcParent, [], false), sb.decl({ ...src, ...styleOv } as DesignNode, srcParent, [], false));
        if (Object.keys(d).length) styles[k] = d;
      }
      if (ov.icon) warnings.push(opts.lang === 'it' ? `L’override dell’icona in “${inst.name}” non è esportato` : `Icon override in “${inst.name}” is not exported`);
    }
    if (Object.keys(texts).length) props.push(`texts={${js(texts)}}`);
    if (Object.keys(visible).length) props.push(`visible={${js(visible)}}`);
    if (Object.keys(images).length) props.push(`images={${js(images)}}`);
    if (Object.keys(styles).length) props.push(`styles={${js(styles)}}`);
    // The instance's own prototype interactions, attached to the component root.
    const clicks = actionsJs(inst.interactions.filter((i) => i.trigger === 'click'));
    const hovers = actionsJs(inst.interactions.filter((i) => i.trigger === 'hover'));
    if (clicks || hovers) {
      u.usesProto = true;
      const handlers: string[] = [];
      if (clicks) {
        handlers.push(`onClick: (e) => { e.stopPropagation(); proto.run(${clicks}, ${scopeExpr(u)}); }`);
        handlers.push(`role: 'button'`, 'tabIndex: 0');
        handlers.push(`onKeyDown: (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); proto.run(${clicks}, ${scopeExpr(u)}); } }`);
      }
      if (hovers) handlers.push(`onMouseEnter: () => proto.hover(${hovers}, true, ${scopeExpr(u)})`, `onMouseLeave: () => proto.hover(${hovers}, false, ${scopeExpr(u)})`);
      props.push(`rootProps={{ ${handlers.join(', ')} }}`);
    }
    void look;
    return `${pad}<${info.name} ${props.join(' ')} />\n`;
  };

  /** Imports for a unit; its own stylesheet comes last so it overrides component styles. */
  const unitImports = (u: Unit, first: string[], css: string) => {
    const lines = [...first];
    if (u.usesProto) lines.push(`import { usePrototype } from '../prototype';`);
    if (u.icons.size) lines.push(`import { ${[...u.icons].sort().map((i) => `${i} as Icon${i}`).join(', ')} } from 'lucide-react';`);
    for (const c of [...u.componentImports].sort()) lines.push(`import { ${c} } from '../components/${c}';`);
    lines.push(`import '${css}';`);
    return lines;
  };

  /* ---------- screens ---------- */
  for (const id of screenIds) {
    const node = project.nodes[id]!;
    const name = screenKey.get(id)!;
    const u = newUnit(`src/screens/${name}.tsx`, camel(name, 's').toLowerCase(), null);
    const body = await render(node, lookup, -1, u, { root: 'screen', parent: null });
    const imports = unitImports(u, [], `./${name}.css`);
    files.push({
      path: u.file,
      content: `${imports.join('\n')}\n\n/** Screen “${node.name.replace(/\*\//g, '')}” — generated by flö. */\nexport function ${name}() {\n${u.usesProto ? '  const proto = usePrototype();\n' : ''}  return (\n${body}  );\n}\n`,
    });
    files.push({ path: `src/screens/${name}.css`, content: u.styles.css() });
  }

  /* ---------- components (generated on demand, including nested ones) ---------- */
  const done = new Set<string>();
  while ([...comps.keys()].some((k) => !done.has(k))) {
    for (const [mainId, info] of [...comps]) {
      if (done.has(mainId)) continue;
      done.add(mainId);
      const u = newUnit(`src/components/${info.name}.tsx`, camel(info.name, 'c').toLowerCase(), info);
      const body = await render(info.main, lookup, -1, u, { root: 'component', parent: null });
      const layerType = info.keys.size ? [...info.keys.values()].map((k) => js(k)).join(' | ') : 'never';
      const textType = info.textKeys.length ? info.textKeys.map((k) => js(k)).join(' | ') : 'never';
      const imageType = info.imageKeys.length ? info.imageKeys.map((k) => js(k)).join(' | ') : 'never';
      const imports = unitImports(u, [`import type { CSSProperties, HTMLAttributes } from 'react';`], `./${info.name}.css`);
      files.push({
        path: u.file,
        content: `${imports.join('\n')}

export type ${info.name}Layer = ${layerType};
export type ${info.name}Text = ${textType};
export type ${info.name}Image = ${imageType};

export interface ${info.name}Props {
  className?: string;
  /** Instance id: scopes prototype show/hide state per instance. */
  pid?: string;
  texts?: Partial<Record<${info.name}Text, string>>;
  visible?: Partial<Record<${info.name}Layer, boolean>>;
  images?: Partial<Record<${info.name}Image, string>>;
  styles?: Partial<Record<${info.name}Layer, CSSProperties>>;
  /** Extra attributes/handlers for the root element (used for instance interactions). */
  rootProps?: HTMLAttributes<HTMLElement>;
}

/** Component “${info.main.name.replace(/\*\//g, '')}” — generated by flö. */
export function ${info.name}(props: ${info.name}Props) {
${u.usesProto ? '  const proto = usePrototype();\n' : ''}  return (
${body}  );
}
`,
      });
      // Component root: strip page positioning; instances provide their own geometry class.
      files.push({ path: `src/components/${info.name}.css`, content: u.styles.css() });
    }
  }
  // Component roots are rendered with root: 'component' → decl was computed as non-root; remove page offsets.
  for (const f of files) {
    if (f.path.startsWith('src/components/') && f.path.endsWith('.css') && typeof f.content === 'string') {
      f.content = f.content.replace(/^(\.[a-z0-9]+-1 \{[\s\S]*?\})/m, (rule) => rule.replace(/\n\s*(left|top|right|bottom): [^;]+;/g, ''));
    }
  }

  /* ---------- app shell ---------- */
  const startId = project.prototype.startFrameId && screenKey.has(project.prototype.startFrameId) ? project.prototype.startFrameId : screenIds[0]!;
  const screenEntries = screenIds.map((id) => `  ${screenKey.get(id)}: { component: ${screenKey.get(id)}, title: ${js(project.nodes[id]!.name)} },`).join('\n');
  files.push({
    path: 'src/App.tsx',
    content: `import { PrototypeProvider, PrototypeView, type ScreenEntry } from './prototype';
${screenIds.map((id) => `import { ${screenKey.get(id)} } from './screens/${screenKey.get(id)}';`).join('\n')}

const screens: Record<string, ScreenEntry> = {
${screenEntries}
};

export default function App() {
  return (
    <PrototypeProvider screens={screens} start=${js(screenKey.get(startId))}>
      <PrototypeView />
    </PrototypeProvider>
  );
}
`,
  });
  files.push({ path: 'src/prototype.tsx', content: PROTOTYPE_RUNTIME });
  files.push({
    path: 'src/main.tsx',
    content: `import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import App from './App';
import './styles/tokens.css';
import './styles/global.css';

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <App />
  </StrictMode>,
);
`,
  });
  files.push({ path: 'src/styles/tokens.css', content: tokensCss(project.tokens) || '/* No design tokens defined in flö. */\n' });
  files.push({ path: 'src/styles/global.css', content: GLOBAL_CSS });

  /* ---------- assets ---------- */
  for (const [assetId, p] of assetPath) {
    const bytes = host.getAssetBytes ? await host.getAssetBytes(assetId) : null;
    if (bytes) files.push({ path: `public${p}`, content: bytes });
    else warnings.push(`Asset ${project.assets[assetId]?.name ?? assetId} could not be read`);
  }

  /* ---------- project files ---------- */
  const usesIcons = files.some((f) => typeof f.content === 'string' && f.content.includes("from 'lucide-react'"));
  const fonts = new Set<string>();
  for (const id of screenIds) {
    const visit = (nid: string) => {
      const n = project.nodes[nid];
      if (!n) return;
      if (n.type === 'text') fonts.add(resolveNode(n, project.tokens, []).fontFamily);
      n.childIds.forEach(visit);
    };
    visit(id);
  }
  for (const c of comps.values()) {
    const visit = (nid: string) => {
      const n = project.nodes[nid];
      if (!n) return;
      if (n.type === 'text') fonts.add(resolveNode(n, project.tokens, []).fontFamily);
      n.childIds.forEach(visit);
    };
    visit(c.main.id);
  }
  const fontHref = fontLinkHref(fonts);
  const pkgName = words(opts.name).join('-').toLowerCase() || 'flo-export';
  files.push({
    path: 'package.json',
    content: `${JSON.stringify(
      {
        name: pkgName,
        private: true,
        version: '0.1.0',
        type: 'module',
        scripts: { dev: 'vite', build: 'tsc --noEmit && vite build', preview: 'vite preview' },
        dependencies: { react: '19.1.1', 'react-dom': '19.1.1', ...(usesIcons ? { 'lucide-react': '0.544.0' } : {}) },
        devDependencies: {
          '@types/react': '19.1.12',
          '@types/react-dom': '19.1.9',
          '@vitejs/plugin-react': '4.7.0',
          typescript: '5.9.2',
          vite: '6.4.5',
        },
      },
      null,
      2,
    )}\n`,
  });
  files.push({
    path: 'tsconfig.json',
    content: `${JSON.stringify(
      {
        compilerOptions: {
          target: 'ES2022',
          lib: ['ES2023', 'DOM', 'DOM.Iterable'],
          module: 'ESNext',
          moduleResolution: 'bundler',
          jsx: 'react-jsx',
          strict: true,
          noUnusedLocals: true,
          skipLibCheck: true,
          isolatedModules: true,
          noEmit: true,
          types: ['vite/client'],
        },
        include: ['src'],
      },
      null,
      2,
    )}\n`,
  });
  files.push({
    path: 'vite.config.ts',
    content: `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({ plugins: [react()] });
`,
  });
  files.push({
    path: 'index.html',
    content: `<!doctype html>
<html lang="${opts.lang}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${opts.name.replace(/[<>&"]/g, '')}</title>
${fontHref ? `    <link rel="preconnect" href="https://fonts.googleapis.com" />\n    <link rel="stylesheet" href="${fontHref}" />\n` : ''}  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`,
  });

  /* ---------- accessibility ---------- */
  const a11y = accessibilityReport(project, screenIds, 'AA', opts.lang);
  const it = opts.lang === 'it';
  files.push({
    path: 'ACCESSIBILITY.md',
    content: `# ${a11y.title}\n\n${it ? 'Livelli controllati' : 'Layers checked'}: ${a11y.checked}\n\n${
      a11y.issues.length ? a11y.issues.map((i) => `- **${i.severity}** — ${i.message}`).join('\n') : it ? 'Nessun problema trovato.' : 'No issues found.'
    }\n\n${it ? 'Il codice generato usa elementi semantici, ruoli e focus da tastiera per gli elementi interattivi.' : 'Generated code uses semantic elements, roles and keyboard focus for interactive elements.'}\n`,
  });
  files.push({
    path: 'README.md',
    content: `# ${opts.name}

${it ? 'Progetto React + TypeScript generato da flö.' : 'React + TypeScript project generated by flö.'}

\`\`\`bash
npm install
npm run dev     # ${it ? 'sviluppo' : 'development'}
npm run build   # ${it ? 'build di produzione in dist/' : 'production build in dist/'}
\`\`\`

## ${it ? 'Struttura' : 'Structure'}

- \`src/screens/\` — ${it ? 'una componente per schermata' : 'one component per screen'} (${screenIds.map((id) => screenKey.get(id)).join(', ')})
- \`src/components/\` — ${it ? 'componenti riutilizzabili (dai componenti flö); le istanze passano gli override come props' : 'reusable components (from flö components); instances pass overrides as props'}
- \`src/styles/tokens.css\` — ${it ? 'token di design come variabili CSS' : 'design tokens as CSS variables'}
- \`src/prototype.tsx\` — ${it ? 'navigazione del prototipo (#/Schermata), overlay, mostra/nascondi' : 'prototype navigation (#/Screen), overlays, show/hide'}
- \`public/assets/\` — ${it ? 'immagini' : 'images'}

${it ? 'Le schermate usano flexbox per l’auto layout e @media per i breakpoint.' : 'Screens use flexbox for auto layout and @media for breakpoints.'}
${warnings.length ? `\n## ${it ? 'Avvisi' : 'Warnings'}\n\n${[...new Set(warnings)].map((w) => `- ${w}`).join('\n')}\n` : ''}`,
  });

  return { files, warnings: [...new Set(warnings)], a11y, screens: screenIds.map((id) => screenKey.get(id)!) };
}

/** Packs export files into a zip archive rooted in a folder. */
export async function zipExport(files: ExportFile[], folder: string): Promise<Uint8Array> {
  const { createZip } = await import('./zip');
  const enc = new TextEncoder();
  return createZip(files.map((f) => ({ path: `${folder}/${f.path}`, data: typeof f.content === 'string' ? enc.encode(f.content) : f.content })));
}
