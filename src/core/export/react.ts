const PROTOTYPE_RUNTIME = `/* Prototype runtime generated by flö: screen navigation, overlays and show/hide. */
import { createContext, useCallback, useContext, useEffect, useMemo, useState, type ComponentType, type ReactNode } from 'react';

export type Transition = { type: 'instant' | 'dissolve' | 'slide-left' | 'slide-right' | 'slide-up' | 'slide-down'; durationMs: number };
export type Action =
  | { type: 'navigate'; to: string; transition: Transition }
  | { type: 'back' }
  | { type: 'open-overlay'; to: string; position: 'center' | 'top' | 'bottom' | 'left' | 'right'; closeOnOutsideClick: boolean; dimBackground: boolean }
  | { type: 'close-overlay' }
  | { type: 'toggle-visibility'; target: string };

type Overlay = Extract<Action, { type: 'open-overlay' }>;

export interface ScreenEntry {
  component: ComponentType;
  title: string;
}

interface State {
  screen: string;
  history: string[];
  overlays: Overlay[];
  visibility: Record<string, boolean>;
  transition: Transition | null;
  direction: 'forward' | 'back';
  nav: number;
}

interface Proto {
  state: State;
  screens: Record<string, ScreenEntry>;
  run: (actions: Action[], scope?: string) => void;
  hover: (actions: Action[], enter: boolean, scope?: string) => void;
  isVisible: (id: string, base: boolean, scope?: string) => boolean;
  closeOverlay: (index: number) => void;
}

const Ctx = createContext<Proto | null>(null);

const key = (id: string, scope?: string) => (scope ? \`\${scope}:\${id}\` : id);

function apply(s: State, a: Action, scope: string | undefined, screens: Record<string, ScreenEntry>, baseOf: (k: string) => boolean): State {
  switch (a.type) {
    case 'navigate':
      if (!screens[a.to] || a.to === s.screen) return s;
      return { screen: a.to, history: [...s.history, s.screen], overlays: [], visibility: {}, transition: a.transition, direction: 'forward', nav: s.nav + 1 };
    case 'back': {
      if (s.overlays.length) return { ...s, overlays: s.overlays.slice(0, -1) };
      const prev = s.history[s.history.length - 1];
      return prev ? { ...s, screen: prev, history: s.history.slice(0, -1), overlays: [], visibility: {}, direction: 'back', nav: s.nav + 1 } : s;
    }
    case 'open-overlay':
      return screens[a.to] && !s.overlays.some((o) => o.to === a.to) ? { ...s, overlays: [...s.overlays, a] } : s;
    case 'close-overlay':
      return { ...s, overlays: s.overlays.slice(0, -1) };
    case 'toggle-visibility': {
      const k = key(a.target, scope);
      return { ...s, visibility: { ...s.visibility, [k]: !(s.visibility[k] ?? baseOf(k)) } };
    }
  }
}

const baseVisibility = new Map<string, boolean>();

function screenFromHash(screens: Record<string, ScreenEntry>): string | null {
  const k = decodeURIComponent(window.location.hash.replace(/^#\\/?/, ''));
  return screens[k] ? k : null;
}

export function PrototypeProvider({ screens, start, children }: { screens: Record<string, ScreenEntry>; start: string; children: ReactNode }) {
  const [state, setState] = useState<State>(() => ({
    screen: screenFromHash(screens) ?? start,
    history: [],
    overlays: [],
    visibility: {},
    transition: null,
    direction: 'forward',
    nav: 0,
  }));
  useEffect(() => {
    const target = \`#/\${encodeURIComponent(state.screen)}\`;
    if (window.location.hash !== target) window.history.replaceState(null, '', target);
    document.title = screens[state.screen]?.title ?? document.title;
  }, [state.screen, screens]);
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') setState((s) => (s.overlays.length ? { ...s, overlays: s.overlays.slice(0, -1) } : s));
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, []);
  const baseOf = useCallback((k: string) => baseVisibility.get(k) ?? true, []);
  const value = useMemo<Proto>(
    () => ({
      state,
      screens,
      run: (actions, scope) => setState((s) => actions.reduce((acc, a) => apply(acc, a, scope, screens, baseOf), s)),
      hover: (actions, enter, scope) =>
        setState((s) =>
          actions.reduce((acc, a) => {
            if (enter || a.type === 'toggle-visibility') return apply(acc, a, scope, screens, baseOf);
            if (a.type === 'open-overlay') return { ...acc, overlays: acc.overlays.filter((o) => o.to !== a.to) };
            return acc;
          }, s),
        ),
      isVisible: (id, base, scope) => {
        const k = key(id, scope);
        baseVisibility.set(k, base);
        return state.visibility[k] ?? base;
      },
      closeOverlay: (index) => setState((s) => ({ ...s, overlays: s.overlays.filter((_, i) => i !== index) })),
    }),
    [state, screens, baseOf],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function usePrototype(): Proto {
  const p = useContext(Ctx);
  if (!p) throw new Error('usePrototype must be used inside <PrototypeProvider>');
  return p;
}

const REVERSE: Record<string, string> = { 'slide-left': 'slide-right', 'slide-right': 'slide-left', 'slide-up': 'slide-down', 'slide-down': 'slide-up' };

export function PrototypeView() {
  const { state, screens, closeOverlay } = usePrototype();
  const Screen = screens[state.screen]!.component;
  const t = state.transition;
  const type = t && state.nav > 0 && t.type !== 'instant' ? (state.direction === 'back' ? (REVERSE[t.type] ?? t.type) : t.type) : null;
  return (
    <div className="flo-stage">
      <div key={state.nav} className="flo-screen" style={type && t ? { animation: \`flo-\${type} \${t.durationMs}ms cubic-bezier(0.2, 0.7, 0.2, 1) both\` } : undefined}>
        <Screen />
      </div>
      {state.overlays.map((o, i) => {
        const Overlay = screens[o.to]!.component;
        return (
          <div
            key={o.to}
            className={\`flo-overlay flo-overlay--\${o.position}\${o.dimBackground ? ' flo-overlay--dim' : ''}\`}
            onClick={() => o.closeOnOutsideClick && closeOverlay(i)}
            role="dialog"
            aria-modal="true"
          >
            <div className="flo-overlay__panel" onClick={(e) => e.stopPropagation()}>
              <Overlay />
            </div>
          </div>
        );
      })}
    </div>
  );
}
`;

