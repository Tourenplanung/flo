import { createPage } from '../factory';
import type { DocOp } from '../ops';
import type { Project } from '../schema';
import type { DesignValue } from './catalog';

export const DEVICES = {
  desktop: { width: 1440, height: 1024, label: 'Desktop' },
  tablet: { width: 768, height: 1024, label: 'Tablet' },
  mobile: { width: 390, height: 844, label: 'Mobile' },
} as const;

export type Device = keyof typeof DEVICES;

export const GAP_BETWEEN_FRAMES = 160;

/** X coordinate to the right of all top-level content on a page. */
export function nextFreeX(project: Project, pageId: string, exclude: Set<string> = new Set()): number {
  const page = project.pages.find((p) => p.id === pageId);
  let x = 0;
  let any = false;
  for (const id of page?.childIds ?? []) {
    if (exclude.has(id)) continue;
    const n = project.nodes[id];
    if (!n) continue;
    any = true;
    x = Math.max(x, n.x + n.width);
  }
  return any ? x + GAP_BETWEEN_FRAMES : 0;
}

/** Ops removing frames generated by a previous run (if they still exist). */
export function removeGenerated(project: Project, prev: DesignValue | undefined): DocOp[] {
  if (!prev) return [];
  return prev.frameIds.filter((id) => project.nodes[id]).map((id) => ({ type: 'deleteNode', id }) as DocOp);
}

/** Finds a page by name or returns ops creating it. */
export function ensurePage(project: Project, name: string): { pageId: string; ops: DocOp[] } {
  const existing = project.pages.find((p) => p.name === name);
  if (existing) return { pageId: existing.id, ops: [] };
  const page = createPage(name);
  return { pageId: page.id, ops: [{ type: 'createPage', page }] };
}

/** Resolves a design value to the frames that still exist. */
export function liveFrames(project: Project, d: DesignValue): string[] {
  return d.frameIds.filter((id) => project.nodes[id]);
}
